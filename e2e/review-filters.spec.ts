import {test,expect} from '@playwright/test';
test('separates learned marks from flashcards and saves a filtered 20-word round',async({page,request})=>{
 const backup=await(await request.get('/api/backup')).json();
 backup.objects=[];backup.events=[];
 await request.post('/api/restore',{headers:{'X-Mandarin-Client':'local-ui'},data:backup});
 await page.goto('/#learn/tw.greetings.lesson.1');
 const word=page.locator('.study-card').first();
 await word.getByRole('button',{name:'Đánh dấu đã học',exact:true}).click();
 expect(Object.keys((await(await request.get('/api/state')).json()).objects.cards)).toHaveLength(0);
 await word.getByRole('button',{name:'+ Thêm vào flashcard',exact:true}).dblclick();
 await expect(word.getByRole('button',{name:'Đã thêm vào flashcard',exact:true})).toBeDisabled();
 expect(Object.keys((await(await request.get('/api/state')).json()).objects.cards)).toHaveLength(1);
 const content=await(await request.get('/api/content')).json();
 const words=content.units.flatMap((u:any)=>u.words.map((w:any)=>({...w,deck:u.title}))).slice(1,65);
 await page.goto('/#notebook');await page.getByRole('button',{name:'Thẻ cá nhân',exact:true}).click();
 await page.locator('input[type=file]').setInputFiles({name:'cards.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({schema:1,cards:words.map((w:any,i:number)=>({id:'filter-test:'+i,word:{hanzi:w.hanzi,pinyin:w.pinyin,vi:w.vi},direction:'recognize',deck:w.deck,tags:[]}))}))});
 await expect(page.getByRole('status')).toContainText('Đã nhập');
 await page.goto('/#review');
 const group=page.getByLabel('Nhóm từ');
 const options=await group.locator('option').allTextContents();
 expect(options.length).toBeGreaterThan(1);
 for(const label of options)expect(Number(label.match(/\((\d+) từ\)/)![1])).toBeGreaterThanOrEqual(20);
 await group.selectOption({index:1});
 await page.getByRole('button',{name:'Lật thẻ',exact:true}).click();
 const shown=await page.locator('.flashcard [lang="zh-TW"]').first().textContent();
 await page.reload();
 await expect(page.locator('.card-question')).toHaveText(shown!);
 await page.getByRole('button',{name:'Lật thẻ',exact:true}).click();
 await page.getByRole('button',{name:'Tiếp →',exact:true}).dblclick();
 await expect(page.getByText('1/20 từ trong lượt',{exact:false})).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
